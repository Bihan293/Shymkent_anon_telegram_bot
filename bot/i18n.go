package main

import "sync"

// ── Language constants ───────────────────────────────────────────────────────
const (
	LangRU = "ru"
	LangKZ = "kz"
)

// ── Language storage (in-memory, keyed by userID) ────────────────────────────
var (
	userLangs map[int64]string
	langMu    sync.Mutex
)

func init() {
	userLangs = make(map[int64]string)
}

func getUserLang(userID int64) string {
	langMu.Lock()
	defer langMu.Unlock()
	l, ok := userLangs[userID]
	if !ok {
		return "" // not chosen yet
	}
	return l
}

func setUserLang(userID int64, lang string) {
	langMu.Lock()
	defer langMu.Unlock()
	userLangs[userID] = lang
}

// ── Translations ─────────────────────────────────────────────────────────────

// t returns the translated string for a given key and language.
func t(lang, key string) string {
	if lang == "" {
		lang = LangRU // fallback
	}
	if m, ok := translations[lang]; ok {
		if s, ok := m[key]; ok {
			return s
		}
	}
	// fallback to Russian
	if s, ok := translations[LangRU][key]; ok {
		return s
	}
	return key
}

